const { TOOLS } = require('./tools');

// One page per sector/industry ETF that the /flow view already tracks
// (server/services/sectorFlow.js). Holdings named here are long-standing,
// well-known constituents; each page says composition changes over time.
function sectorPage({ slug, etf, name, h1, description, intro, what, drivers, behaviour, examples, related }) {
  return {
    slug,
    category: 'sectors',
    h1,
    title: `${name} — סקטור ${etf} בשוק האמריקאי | Capital Flow`,
    description,
    intro,
    sections: [
      { h: `מה כולל ${name}`, body: what },
      {
        h: 'חברות בולטות',
        body: [`בין החברות המוכרות בתחום (ההרכב והמשקלות בקרנות משתנים לאורך זמן): ${examples}.`],
      },
      { h: 'מה מזיז את הסקטור', body: [{ list: drivers }] },
      { h: 'איך הסקטור מתנהג', body: behaviour },
      {
        h: `איך עוקבים אחרי ${name} עם ${etf}`,
        body: [
          `קרן הסל ${etf} משמשת כמדד ייחוס פשוט לתחום. כשהיא זזה בנפח גבוה מהרגיל, הפעילות כנראה רחבה ולא מוגבלת למניה אחת.`,
          {
            steps: [
              `בודקים את ${etf} בתצוגת הסקטורים — שינוי מחיר ויחס נפח.`,
              'משווים לסקטורים אחרים: האם התחום מוביל או מפגר היום?',
              'סורקים את מניות התחום בסורק הנפח כדי לראות אילו מניות מובילות את התנועה.',
            ],
          },
        ],
      },
    ],
    tool: TOOLS.flow,
    faq: [
      {
        q: `מה זה ${etf}?`,
        a: `${etf} היא קרן סל שמחזיקה מניות של חברות מתחום ${name.replace('סקטור ', '').replace('ענף ', '')}, ומשמשת דרך נפוצה לעקוב אחרי התחום כולו.`,
      },
      {
        q: `האם תנועה ב-${etf} אומרת שכל המניות בתחום זזות?`,
        a: 'לא בהכרח. בקרנות שמשוקללות לפי שווי שוק, כמה חברות גדולות יכולות להזיז את רוב הקרן. כדאי לבדוק גם את המניות עצמן.',
      },
    ],
    related: related.concat(['market-sectors', 'sector-flow']),
  };
}

